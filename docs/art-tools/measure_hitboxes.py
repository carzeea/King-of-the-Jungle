"""Measure every fighter's body width and attack reach straight from the HD sprite art.
Writes game/js/hitboxes.js (window.KOTJ_HIT). Re-run after any new sprite sheets go in:
    python3 docs/art-tools/measure_hitboxes.py
Units are game units, measured from the fighter's centre (anchor) toward the way they face.
  body  = [front, back]  how far the torso sticks out in front / behind (idle frames, chest-to-hip rows)
  reach = {anim: [reach, height]}  furthest point of the attack art and how high it is (for spark placement)
"""
import json, re, os, numpy as np
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), '..', '..', 'game')
HD = json.loads(re.search(r"SPRITES_HD=(\{.*\});?\s*$", open(os.path.join(ROOT, 'js/sprites-hd.js')).read(), re.S).group(1).rstrip(';'))
out = {}
for fid, d in HD.items():
    sc = d.get('s', .8); A = d['anims']
    def frames(name):
        m = A[name]; n, fw, fh, px, py = m[:5]; cols = m[5] if len(m) > 5 else n
        im = np.array(Image.open(os.path.join(ROOT, f'assets/characters/{fid}/frames-hd/{name}.webp')).convert('RGBA'))[..., 3] > 110
        return [im[(i//cols)*fh:(i//cols+1)*fh, (i%cols)*fw:(i%cols+1)*fw] for i in range(n)], px, py
    # body: torso rows only (between 30% and 80% of figure height), median edge per frame
    fr, px, py = frames('idle'); fronts = []; backs = []
    for f in fr:
        rows = np.where(f.any(1))[0]
        if not len(rows): continue
        t, b = rows.min(), rows.max(); band = f[int(t + (b-t)*.30):int(t + (b-t)*.80)]
        r = [np.where(x)[0] for x in band if x.any()]
        fronts.append(np.median([c.max() for c in r]) / sc - px); backs.append(px - np.median([c.min() for c in r]) / sc)
    front, back = float(np.median(fronts)), float(np.median(backs))
    reach = {}
    for name in A:
        if name in ('fall','idle', 'walk_forward', 'walk_back', 'run', 'crouch', 'jump', 'block', 'hit_light', 'hit_heavy', 'knockdown_getup', 'victory', 'defeat', 'breathing', 'dash'):
            continue
        fr, px, py = frames(name); best = (0, 160)
        for f in fr:
            cols = np.where(f.any(0))[0]
            if not len(cols): continue
            x = cols.max(); r = cols.max() / sc - px
            if r > best[0]:
                ys = np.where(f[:, max(0, x-6):x+1].any(1))[0]
                best = (r, py - ys.mean() / sc + 6)
        # ignore effect trails far beyond the body (swooshes, dust): cap the reach
        reach[name] = [round(min(best[0], front + 210)), round(max(40, min(320, best[1])))]
    out[fid] = {'body': [round(front), round(back)], 'reach': reach}
js = '// Generated by docs/art-tools/measure_hitboxes.py from the sprite art. Do not edit by hand.\nwindow.KOTJ_HIT=' + json.dumps(out, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'js/hitboxes.js'), 'w').write(js)
for k, v in out.items():
    print(f"{k:10s} body {v['body']}  light {v['reach'].get('attack_light')}  heavy {v['reach'].get('attack_heavy')}  bite {v['reach'].get('bite')}  upper {v['reach'].get('uppercut')}")
